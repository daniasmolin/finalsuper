class Тварина:
    def __init__(self, назва, вік):
        self.назва = назва
        self.вік = вік

    def видати_звук(self):
        return "Якийсь звук"

    def їсти(self):
        return f"{self.назва} зараз їсть."


class Собака(Тварина):
    def __init__(self, назва, вік, порода):
        super().__init__(назва, вік)
        self.порода = порода

    def видати_звук(self):
        return "Гав-гав!"

    def приносити_палицю(self):
        return f"{self.назва} приніс палицю!"


class Кіт(Тварина):
    def __init__(self, назва, вік, колір_шерсті):
        super().__init__(назва, вік)
        self.колір_шерсті = колір_шерсті

    def видати_звук(self):
        return "Мяу!"

    def мурчати(self):
        return f"{self.назва} задоволено мурчить."


if __name__ == "__main__":
    пес = Собака("Рекс", 3, "Німецька вівчарка")
    кіт = Кіт("Барсик", 2, "Рудий")

    print(f"Собака: {пес.назва}, Вік: {пес.вік}, Порода: {пес.порода}")
    print(f"Звук: {пес.видати_звук()}")
    print(пес.їсти())
    print(пес.приносити_палицю())

    print("-" * 30)

    print(f"Кіт: {кіт.назва}, Вік: {кіт.вік}, Колір: {кіт.колір_шерсті}")
    print(f"Звук: {кіт.видати_звук()}")
    print(кіт.їсти())
    print(кіт.мурчати())